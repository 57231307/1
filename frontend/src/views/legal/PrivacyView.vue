      <h2>一、政策适用范围</h2>
      <p>本《隐私政策》适用于用户在使用本纺织印染企业资源计划（ERP）管理系统（以下简称"本系统"）过程中涉及的个人信息处理行为。本政策与《用户服务协议》配套使用，用户在登录系统前须同时勾选同意《用户服务协议》与本《隐私政策》。</p>
      <p>本政策依据《中华人民共和国个人信息保护法》（以下简称《个人信息保护法》）、《中华人民共和国数据安全法》（以下简称《数据安全法》）、《中华人民共和国网络安全法》（以下简称《网络安全法》）及相关行政法规制定。</p>
    </section>

    <section>
      <h2>二、个人信息定义</h2>
      <p>本政策所称"个人信息"，是指以电子方式记录的与已识别或可识别的自然人有关的各种信息，包括但不限于姓名、联系方式、账号信息、位置信息、行为记录等。</p>
      <p>"敏感个人信息"是指一旦泄露或被非法使用，容易导致自然人的人格尊严受到侵害或者人身、财产安全受到危害的个人信息，包括生物识别、宗教信仰、特定身份、医疗健康、金融账户、行踪轨迹等，以及不满十四周岁未成年人的个人信息。本系统处理的个人信息中涉及员工账号、操作行为轨迹、财务数据等，部分属于敏感个人信息范畴。</p>
    </section>

    <section>
      <h2>三、信息采集内容</h2>
      <p>本系统采集以下个人信息：</p>
      <p>1. <strong>身份识别信息</strong>：用户名、真实姓名、所属部门、角色权限标识、用户ID。上述信息由运营方系统管理员在创建账号时录入，用于身份认证与权限分配。</p>
      <p>2. <strong>认证凭证信息</strong>：密码（经哈希加密存储）、双因素认证TOTP密钥（base32编码，绑定后存储）、恢复码（加密存储）。系统不存储密码明文。</p>
      <p>3. <strong>设备与网络信息</strong>：登录时的IP地址、User-Agent（浏览器类型与版本）、请求追踪ID（X-Request-Id）。上述信息用于安全审计与异常登录检测。</p>
      <p>4. <strong>操作行为信息</strong>：用户在系统内的全部API请求记录，包括请求方法（GET/POST/PUT/DELETE）、请求路径、操作类型分类（READ/CREATE/UPDATE/DELETE/PRINT/EXPORT/DOWNLOAD/APPROVE）、资源类型、操作时间戳、请求参数摘要、响应状态码、响应耗时。上述信息写入全量审计日志（omni_audit_logs）。</p>
      <p>5. <strong>业务操作数据</strong>：用户在系统中录入或处理的客户信息、供应商信息、产品信息、染料配方、价格策略、订单数据、财务凭证等业务数据。这些数据中的客户联系人姓名、电话、地址等属于个人信息。</p>
    </section>

    <section>
      <h2>四、信息采集目的与法律依据</h2>
      <p>本系统采集个人信息的法律依据及目的如下：</p>
      <p>1. <strong>履行法定义务</strong>：依据《网络安全法》第二十一条、《数据安全法》第三十一条，网络运营者应当留存网络日志不少于六个月。系统采集操作行为信息用于满足法定审计留痕义务。</p>
      <p>2. <strong>履行合同义务</strong>：用户作为运营方员工或被授权使用人，其身份信息、认证凭证的采集是为履行劳动关系或授权使用关系项下的合同义务，用于身份认证、权限控制与业务功能实现。</p>
      <p>3. <strong>安全防护目的</strong>：设备与网络信息、登录锁定记录的采集用于防范暴力破解、异常登录检测及账号安全保护。</p>
      <p>4. <strong>合规审计目的</strong>：审计日志的采集用于满足《数据安全法》数据安全审计要求及运营方内部合规需求，确保操作可追溯、责任可落实。</p>
      <p>系统采集个人信息遵循最小必要原则，不采集与上述目的无关的信息。</p>
    </section>

    <section>
      <h2>五、信息存储与安全</h2>
      <p>1. <strong>存储地点</strong>：本系统数据存储于运营方部署的服务器及关联数据库中，存储地点位于中华人民共和国境内。系统不向境外传输个人信息。</p>
      <p>2. <strong>存储期限</strong>：业务数据在用户账号存续期间持续存储；用户离职或账号停用后，业务数据按运营方数据管理政策保留，审计日志保留期限不少于六个月（法定最低年限），敏感数据导出审计记录（audit_log_export_log）永久保留。</p>
      <p>3. <strong>安全技术措施</strong>：系统采取以下安全措施保护个人信息：</p>
      <ul>
        <li>密码哈希加密存储，不存储明文密码；</li>
        <li>双因素认证（TOTP）密钥绑定后存储，登录时动态生成验证码；</li>
        <li>访问令牌（access_token）与CSRF令牌通过httpOnly Cookie传递，前端不可读，防止XSS窃取；</li>
        <li>PostgreSQL行级安全（RLS）策略，用户仅可访问所属部门及角色权限范围内可见的数据，数据库层面强制隔离；</li>
        <li>登录安全锁定机制（IP维度9次/账号维度18次，锁定30分钟），防范暴力破解；</li>
        <li>全量操作审计，用户操作行为全程记录且通过数据库触发器实施防篡改保护；</li>
        <li>敏感数据导出二级审批与一次性令牌（5分钟有效期），防止数据批量泄露。</li>
      </ul>
      <p>4. <strong>数据加密传输</strong>：系统在生产环境通过HTTPS加密传输全部数据，防止传输过程中被截获篡改。</p>
    </section>

