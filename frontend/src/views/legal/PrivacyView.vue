      <h2>第九条 敏感数据导出管控</h2>
      <p>系统对客户数据、供应商数据、染料配方、价格清单、财务报表、审计日志六类敏感资源实施强制二级审批导出控制：</p>
      <p>9.1 <strong>审批流程</strong>：用户须提交导出审批申请，经一级审批人（直接上级）和二级审批人（部门经理或更高权限）逐级审批通过后方可导出。</p>
      <p>9.2 <strong>令牌管控</strong>：审批通过后系统生成一次性下载令牌，有效期5分钟，与申请导出的资源类型绑定，不可跨资源复用，使用后立即失效。</p>
      <p>9.3 <strong>水印追踪</strong>：所有导出文件内嵌操作员用户名、导出时间戳及资源类型水印。导出操作同时写入审计日志及独立防篡改表，用户无法篡改导出记录。</p>
      <p>9.4 <strong>fail-closed校验</strong>：全部导出端点实施无令牌即拒绝的强制校验，无任何后门或豁免路径。未经审批的导出请求直接返回HTTP 403拒绝。</p>
      <p>9.5 <strong>导出数据责任</strong>：用户通过审批合法导出的数据中可能包含客户个人信息（姓名、电话、地址），用户应确保对该等个人信息的使用符合《个人信息保护法》规定，并承担因存储、使用不当导致泄露的责任。</p>
