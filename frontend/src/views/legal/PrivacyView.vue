      <p>8.1 <strong>内部共享</strong>：用户个人信息在运营方内部按角色权限共享：</p>
      <ul>
        <li>系统管理员：可查看全部用户账号信息；</li>
        <li>部门经理：可查看本部门成员的操作审计记录；</li>
        <li>普通用户：仅可查看本人相关信息。</li>
      </ul>
      <p>8.2 <strong>第三方共享</strong>：本系统不向第三方共享用户个人信息，但以下情形除外：</p>
      <ul>
        <li>经用户单独同意的；</li>
        <li>为委托处理目的与受托方签订数据处理协议的（受托方须按本政策同等标准保护数据，且不得超出约定目的处理）；</li>
        <li>法律法规要求或行政、司法机关依法要求披露的。</li>
      </ul>
      <p>【法律依据】《个人信息保护法》第二十三条："个人信息处理者向其他个人信息处理者提供其处理的个人信息的，应当向个人告知接收方的名称或者姓名、联系方式、处理目的、处理方式和个人信息的种类，并取得个人的单独同意。"第二十一条第一款："个人信息处理者委托处理个人信息的，应当与受托人约定委托处理的目的、期限、处理方式、个人信息的种类、保护措施以及双方的权利和义务等，并对受托人的个人信息处理活动进行监督。"第二十一条第三款："未经个人信息处理者同意，受托人不得转委托他人处理个人信息。"</p>
      <p>8.3 <strong>转让</strong>：如运营方发生合并、收购或资产转让，涉及个人信息转让的，运营方将依照《个人信息保护法》第二十二条规定，事先告知用户转让目的、受让方名称及联系方式，并取得用户单独同意（法定不需同意的情形除外）。</p>
      <p>8.4 <strong>公开披露</strong>：运营方不主动公开披露用户个人信息。如因法律要求须公开披露的，运营方将依照《个人信息保护法》相关规定评估披露必要性及合法性，并告知用户披露目的与对象。</p>
