      <h2>第十条 审计日志与操作留痕</h2>
      <p>10.1 <strong>审计内容</strong>：系统对用户的全部API请求实施全量审计，审计日志包含以下信息：用户ID、用户名、角色、操作类型分类（READ/CREATE/UPDATE/DELETE/PRINT/EXPORT/DOWNLOAD/APPROVE）、资源类型、资源ID、请求方法、请求路径、查询参数、请求体摘要、响应状态码、响应耗时、IP地址、User-Agent、时间戳（UTC）、请求追踪ID。</p>
      <p>10.2 <strong>防篡改保护</strong>：审计日志通过数据库 BEFORE UPDATE / DELETE 触发器实施防篡改保护，用户（含系统管理员）均无法修改或删除已生成的审计记录。敏感数据导出操作另写入独立的 audit_log_export_log 防篡改表。</p>
      <p>10.3 <strong>SHA256指纹</strong>：审计日志导出文件在生成时计算SHA256指纹并写入防篡改表，任何对导出文件的后续篡改均可通过与指纹比对发现。</p>
      <p>10.4 <strong>采集目的</strong>：审计日志的采集目的为：满足法定网络日志留存义务（不少于六个月）、合规审计需求、异常行为检测、安全事件追溯。审计日志不用于商业分析或用户画像。</p>
      <p>10.5 <strong>查询权限</strong>：普通用户可查看与自己相关的审计记录；系统管理员可查看全部审计记录；部门经理可查看本部门成员的操作记录。查询审计记录须具有 audit-logs:read 权限。</p>
    </section>

