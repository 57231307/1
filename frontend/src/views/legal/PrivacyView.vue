      <h2>第十一条 行级数据安全（RLS）</h2>
      <p>11.1 <strong>RLS策略</strong>：系统通过PostgreSQL行级安全（RLS）策略实现数据隔离。RLS策略谓词在数据库层面强制执行，确保用户仅可访问其所属部门及角色权限范围内可见的业务数据行。</p>
      <p>11.2 <strong>部门归属</strong>：用户所在部门及兼职部门信息由运营方系统管理员维护，用户不得自行修改部门归属。RLS策略基于用户的部门归属（含主部门、兼职部门及子部门）动态计算可见数据范围。</p>
      <p>11.3 <strong>公海数据</strong>：部分业务数据（如客户公海、线索公海）具有公海属性，归属列为空或特定值的记录允许全部用户访问，具体规则以运营方业务策略为准。</p>
      <p>11.4 <strong>应用层与数据库层双控</strong>：系统在应用层（条件构造）与数据库层（RLS策略）双重实施数据安全控制，任一层面失效不影响另一层面的保护。</p>
    </section>

