      <h2>第六条 安全技术措施</h2>
      <p>系统采取以下安全技术措施保护个人信息：</p>
      <p>6.1 <strong>密码安全</strong>：密码经Argon2哈希加密存储，不存储明文，运营方及系统管理员均无法获取密码原文。</p>
      <p>6.2 <strong>双因素认证</strong>：支持基于时间的一次性密码（TOTP，RFC 6238）双因素认证。TOTP密钥绑定后存储，登录时动态生成验证码，防止密码泄露后的账号被盗用。</p>
      <p>6.3 <strong>httpOnly Cookie</strong>：访问令牌（access_token）与CSRF令牌通过httpOnly Cookie传递，前端JavaScript不可读取，防止XSS攻击窃取令牌。</p>
      <p>6.4 <strong>行级安全（RLS）</strong>：系统通过PostgreSQL行级安全策略实现数据隔离，用户仅可访问所属部门及角色权限范围内可见的数据行。该隔离在数据库层面强制执行，即使用户直接连接数据库执行SQL查询也无法越权读取。</p>
      <p>6.5 <strong>登录锁定机制</strong>：实施登录安全锁定策略——同一IP连续登录失败达到9次锁定30分钟，同一账号连续登录失败达到18次锁定30分钟，防范暴力破解。</p>
      <p>6.6 <strong>全量操作审计</strong>：用户操作行为全程记录且通过数据库触发器实施防篡改保护。用户（含系统管理员）均无法修改或删除已生成的审计记录。</p>
      <p>6.7 <strong>敏感数据导出管控</strong>：六类敏感资源实施二级审批与一次性令牌（5分钟有效期），防止数据批量泄露。</p>
      <p>6.8 <strong>水印追踪</strong>：所有导出文件内嵌操作员用户名、导出时间戳及资源类型水印。导出操作写入独立防篡改表，用户无法篡改导出记录。</p>
      <p>6.9 <strong>HTTPS加密传输</strong>：系统在生产环境通过HTTPS加密传输全部数据，防止传输过程中被截获篡改。</p>
      <p>6.10 <strong>数据备份</strong>：运营方定期备份系统数据，备份介质与生产环境隔离存储。</p>
