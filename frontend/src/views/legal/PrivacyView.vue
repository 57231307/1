    <section>
      <h2>七、信息共享与披露</h2>
      <p>1. <strong>内部共享</strong>：用户个人信息在运营方内部按角色权限共享。系统管理员可查看全部用户账号信息；部门经理可查看本部门成员的操作审计记录；普通用户仅可查看本人相关信息。</p>
      <p>2. <strong>第三方共享</strong>：本系统不向第三方共享用户个人信息，但以下情形除外：</p>
      <ul>
        <li>经用户单独同意的；</li>
        <li>为委托处理目的与受托方签订数据处理协议的（受托方须按本政策同等标准保护数据）；</li>
        <li>法律法规要求或行政/司法机关依法要求披露的。</li>
      </ul>
      <p>3. <strong>公开披露</strong>：运营方不主动公开披露用户个人信息。如因法律要求须公开披露的，运营方将依照《个人信息保护法》相关规定评估披露必要性及合法性。</p>
    </section>

    <section>
      <h2>八、敏感数据导出管控</h2>
      <p>系统对客户数据、供应商数据、染料配方、价格清单、财务报表、审计日志六类敏感资源实施强制二级审批导出控制：</p>
      <p>1. <strong>审批流程</strong>：用户须提交导出审批申请，经一级审批人（直接上级）和二级审批人（部门经理或更高权限）逐级审批通过后方可导出。</p>
      <p>2. <strong>令牌管控</strong>：审批通过后系统生成一次性下载令牌，有效期5分钟，与申请导出的资源类型绑定，不可跨资源复用，使用后立即失效。</p>
      <p>3. <strong>水印追踪</strong>：所有导出文件内嵌操作员用户名、导出时间戳及资源类型说明水印。导出操作同时写入审计日志及独立防篡改表，用户无法篡改自身导出记录。</p>
      <p>4. <strong>fail-closed校验</strong>：全部导出端点实施无令牌即拒绝的强制校验，无任何后门或豁免路径。未经审批的导出请求直接返回403拒绝。</p>
      <p>用户通过审批合法导出的数据中可能包含客户个人信息（姓名、电话、地址），用户应确保导出数据的存储安全，防止个人信息泄露。</p>
    </section>

    <section>
      <h2>九、审计日志与操作留痕</h2>
      <p>系统对用户的全部API请求实施全量审计，审计日志包含以下信息：用户ID、用户名、角色、操作类型分类（READ/CREATE/UPDATE/DELETE/PRINT/EXPORT/DOWNLOAD/APPROVE）、资源类型、资源ID、请求方法、请求路径、查询参数、请求体摘要、响应状态码、响应耗时、IP地址、User-Agent、时间戳、请求追踪ID。</p>
      <p>审计日志通过数据库BEFORE UPDATE/DELETE触发器实施防篡改保护，用户（含系统管理员）均无法修改或删除已生成的审计记录。敏感数据导出操作另写入独立的audit_log_export_log防篡改表。</p>
      <p>审计日志的采集目的为：满足法定网络日志留存义务、合规审计需求、异常行为检测、安全事件追溯。审计日志不用于商业分析或用户画像。</p>
    </section>

    <section>
      <h2>十、用户权利</h2>
      <p>依照《个人信息保护法》第四十四条至第五十条，用户对其个人信息享有以下权利：</p>
      <p>1. <strong>知情权与决定权</strong>：用户有权知悉系统采集其个人信息的种类、目的及方式，有权限制或拒绝非必要的信息采集。但拒绝采集可能影响系统登录与业务功能使用。</p>
      <p>2. <strong>查询权与复制权</strong>：用户有权向运营方查询其个人信息处理情况。用户可通过系统查看本人的操作审计记录（普通用户可查看自己相关记录，管理员可查看全部）。</p>
      <p>3. <strong>更正权</strong>：用户发现系统中其个人信息有误的，有权要求运营方更正。账号信息（姓名、部门）变更由系统管理员操作更新。</p>
      <p>4. <strong>删除权</strong>：用户在以下情形有权要求运营方删除其个人信息：处理目的已实现、无法实现或为实现处理目的不再必要；运营方停止提供产品或服务；用户撤回同意。但法定审计日志留存义务（不少于六个月）及敏感数据导出审计记录（永久保留）项下的信息，依法不予删除。</p>
      <p>5. <strong>账号注销权</strong>：用户离职或不再使用系统时，有权要求运营方停用其账号。停用后用户无法登录系统，但其业务数据与审计记录按本政策第五条规定的保留期限继续存储。</p>
      <p>6. <strong>撤回同意权</strong>：用户有权撤回此前对个人信息处理的同意。但撤回同意不影响撤回前已处理信息的合法性。用户撤回同意可能导致无法继续使用系统。</p>
      <p>用户行使上述权利的，应通过系统管理员或运营方指定渠道提出申请，运营方将在合理期限内处理并答复。</p>
    </section>

    <section>
      <h2>十一、未成年人保护</h2>
