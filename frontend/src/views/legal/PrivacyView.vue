        <li>基于角色的访问控制（RBAC）与行级数据安全控制（RLS）；</li>
        <li>业务功能实现（客户管理、采购销售、财务核算等）；</li>
        <li>安全审计与合规留痕；</li>
        <li>异常行为检测与账号安全保护；</li>
        <li>系统运行状态监控与性能优化。</li>
      </ul>
      <p>系统不将用户个人信息用于用户授权范围以外的用途，不用于商业营销或用户画像分析。</p>
