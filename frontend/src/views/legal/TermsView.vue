      <h2>第六条 登录锁定机制</h2>
      <p>6.1 <strong>IP维度锁定</strong>：同一IP地址连续登录失败达到9次时，系统自动锁定该IP地址30分钟。锁定期间，来自该IP地址的全部登录请求将被拒绝。</p>
      <p>6.2 <strong>账号维度锁定</strong>：同一账号连续登录失败达到18次（IP维度阈值的2倍）时，系统自动锁定该账号30分钟。锁定期间，该账号在任意IP地址的登录请求均被拒绝。</p>
      <p>6.3 <strong>锁定时长</strong>：锁定时长固定为30分钟，自最后一次失败登录之时起算。锁定期间用户无法登录系统，此为安全保护措施，用户不得因此主张运营方违约或要求赔偿。</p>
      <p>6.4 <strong>锁定查询</strong>：用户可在登录页面通过输入用户名查询当前锁定状态（该查询为公开语义，不泄露除失败计数以外的敏感信息）。系统对 lock-status 端点实施 OptionalAuthContext 认证，匿名用户可查询指定用户名的锁定状态。</p>
      <p>6.5 <strong>锁定阈值调整</strong>：运营方有权根据安全态势调整锁定阈值，调整后将通过系统通知方式告知用户。</p>
